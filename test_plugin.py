def _win_font(*names):
    for n in names:
        if os.path.exists(n):
            return n
    return None


def _needs_win_font(*names):
    hit = _win_font(*names)
    return unittest.skipUnless(
        hit is not None, f"缺系统字体 {'/'.join(names)}，跳过"
    )


